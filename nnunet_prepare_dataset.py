"""Build an nnU-Net raw dataset for PSMA PET lesion segmentation.

Source layout (PSMAReg):
    imagesTr/PSMARegPSMA_0006_0000_01.nii.gz   CT,  timepoint 01
    imagesTr/PSMARegPSMA_0006_0001_01.nii.gz   PET, timepoint 01
    labelsTr/PSMARegPSMA_0006_0001_01.nii.gz   PSMA lesion label

nnU-Net layout (case id folds the timepoint into the name, modality goes last):
    imagesTr/PSMARegPSMA_0006_01_0000.nii.gz   CT
    imagesTr/PSMARegPSMA_0006_01_0001.nii.gz   PET
    labelsTr/PSMARegPSMA_0006_01.nii.gz        label

Images are symlinked, so this costs no disk space.
"""

import json
import os
from typing import Dict, List, Tuple

DATA_ROOT = "/home/iml/fryderyk.koegl/data/PSMAReg/PSMAReg_dataset"
IMAGES_DIR = os.path.join(DATA_ROOT, "imagesTr")
LABELS_DIR = os.path.join(DATA_ROOT, "labelsTr")
PSMAREG_SPLIT_JSON = os.path.join(DATA_ROOT, "psmareg_split.json")

# The registration split, so nnU-Net trains and is evaluated on exactly the same
# cases as the registration network's segmentation head.
LAPIRN_SPLIT_JSON = "/home/iml/fryderyk.koegl/code/LapIRN-koegl/split.json"
SUBJECT_PREFIX = "PSMARegPSMA_"

NNUNET_RAW = "/home/iml/fryderyk.koegl/code/autopet-3-submission/nnUNet_raw"
NNUNET_PREPROCESSED = "/home/iml/fryderyk.koegl/data/PSMAReg-nnunet/nnUNet_preprocessed"
DATASET_NAME = "Dataset501_PSMALesion"


def source_case_name(subject: str, timepoint: str) -> str:
    """PET filename in the source dataset."""
    return f"{subject}_0001_{timepoint}.nii.gz"


def collect_subject_cases(subject: str) -> List[Tuple[str, str]]:
    """Return (case_id, timepoint) for every labelled PET scan of a subject."""
    cases = []
    prefix = f"{subject}_0001_"
    for name in sorted(os.listdir(LABELS_DIR)):
        if not name.startswith(prefix) or not name.endswith(".nii.gz"):
            continue
        timepoint = name[len(prefix) : -len(".nii.gz")]
        cases.append((f"{subject}_{timepoint}", timepoint))
    return cases


def labelled_subjects() -> set:
    """Subjects that actually have at least one PET lesion label on disk."""
    return {
        name.split("_0001_")[0]
        for name in os.listdir(LABELS_DIR)
        if "_0001_" in name and name.endswith(".nii.gz")
    }


def split_subjects() -> Dict[str, List[str]]:
    """Subject-level split mirroring the registration network's split.

    Train  = LapIRN split.json "train" + all single-timepoint (unpaired) subjects,
             which is how the registration training set is assembled.
    Val    = LapIRN split.json "val". These are the held-out cases the three
             segmentation methods are compared on, and they have real labels.

    Deliberately NOT used for evaluation: imagesVal. Its PET tumour labels were
    generated by the autoPET challenge model, so scoring against them would give
    that model a Dice of ~1.0 by construction and would measure agreement with
    autoPET rather than accuracy.

    split.json's "test" subjects have no PET labels at all, so they play no role
    here.
    """
    with open(LAPIRN_SPLIT_JSON) as f:
        lapirn = json.load(f)
    with open(PSMAREG_SPLIT_JSON) as f:
        psmareg = json.load(f)

    labelled = labelled_subjects()
    unpaired = {e["subject"] for e in psmareg["train_unpaired"]}

    def to_subjects(ids: List[str]) -> set:
        return {SUBJECT_PREFIX + i for i in ids}

    train = (to_subjects(lapirn["train"]) | unpaired) & labelled
    val = to_subjects(lapirn["val"]) & labelled

    overlap = train & val
    assert not overlap, f"subject leakage between train and val: {sorted(overlap)}"
    unassigned = labelled - train - val
    assert not unassigned, f"labelled subjects in neither split: {sorted(unassigned)}"

    return {"train": sorted(train), "val": sorted(val)}


def link(src: str, dst: str) -> None:
    if os.path.islink(dst) or os.path.exists(dst):
        os.remove(dst)
    os.symlink(src, dst)


def main() -> None:
    dataset_dir = os.path.join(NNUNET_RAW, DATASET_NAME)
    images_out = os.path.join(dataset_dir, "imagesTr")
    labels_out = os.path.join(dataset_dir, "labelsTr")
    os.makedirs(images_out, exist_ok=True)
    os.makedirs(labels_out, exist_ok=True)

    subjects = split_subjects()
    case_ids: Dict[str, List[str]] = {"train": [], "val": []}

    for group in ("train", "val"):
        for subject in subjects[group]:
            for case_id, timepoint in collect_subject_cases(subject):
                case_ids[group].append(case_id)
                pet_src = os.path.join(IMAGES_DIR, source_case_name(subject, timepoint))
                ct_src = pet_src.replace("_0001_", "_0000_")
                label_src = os.path.join(
                    LABELS_DIR, source_case_name(subject, timepoint)
                )
                for src in (ct_src, pet_src, label_src):
                    assert os.path.isfile(src), f"missing source file: {src}"
                link(ct_src, os.path.join(images_out, f"{case_id}_0000.nii.gz"))
                link(pet_src, os.path.join(images_out, f"{case_id}_0001.nii.gz"))
                link(label_src, os.path.join(labels_out, f"{case_id}.nii.gz"))

    n_training = len(case_ids["train"]) + len(case_ids["val"])

    # Channel 1 is deliberately declared as "CT" so nnU-Net picks CTNormalization
    # (dataset-global percentile clip + global mean/std) rather than per-image
    # z-scoring, which would destroy absolute SUV. This mirrors the autoPET-3
    # plan, whose normalization_schemes are ['CTNormalization', 'CTNormalization'].
    dataset_json = {
        "channel_names": {"0": "CT", "1": "CT"},
        "labels": {"background": 0, "lesion": 1},
        "numTraining": n_training,
        "file_ending": ".nii.gz",
        "description": "PSMA PET lesion segmentation (CT + PET), PSMAReg cohort.",
    }
    with open(os.path.join(dataset_dir, "dataset.json"), "w") as f:
        json.dump(dataset_json, f, indent=2)

    # nnU-Net reads splits_final.json from the *preprocessed* folder and will not
    # overwrite it if it already exists. One entry = fold 0 only.
    preprocessed_dir = os.path.join(NNUNET_PREPROCESSED, DATASET_NAME)
    os.makedirs(preprocessed_dir, exist_ok=True)
    with open(os.path.join(preprocessed_dir, "splits_final.json"), "w") as f:
        json.dump([{"train": case_ids["train"], "val": case_ids["val"]}], f, indent=2)

    # The held-out cases, recorded under their *source* filenames so the same
    # evaluation code as inference_all.py can consume them. These are the cases
    # all three segmentation methods get compared on.
    with open(os.path.join(dataset_dir, "eval_cases.json"), "w") as f:
        json.dump(
            {
                "subjects": subjects["val"],
                "case_ids": case_ids["val"],
                "source_filenames": [
                    f"{cid.rsplit('_', 1)[0]}_0001_{cid.rsplit('_', 1)[1]}.nii.gz"
                    for cid in case_ids["val"]
                ],
            },
            f,
            indent=2,
        )

    print(f"dataset:    {dataset_dir}")
    for group in ("train", "val"):
        print(
            f"  {group:5s} {len(subjects[group]):4d} subjects  "
            f"{len(case_ids[group]):4d} cases"
        )
    print(f"  numTraining (all linked cases): {n_training}")
    print(f"splits_final.json -> {preprocessed_dir}")
    print(f"eval cases       -> {os.path.join(dataset_dir, 'eval_cases.json')}")


if __name__ == "__main__":
    main()
